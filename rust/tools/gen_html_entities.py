"""Writes rust/crates/lexo-core/src/htmlentities.rs: the tables behind Python's `html.unescape` (the HTML 5 named references, the replacements of invalid numeric
references and the code points that are dropped), so the Rust port of `mt` unescapes exactly like Python.

    py rust/tools/gen_html_entities.py
"""
import html
import html.entities
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "crates" / "lexo-core" / "src" / "htmlentities.rs"


def lit(s):
    return '"' + "".join(c if c.isascii() and c.isprintable() and c not in '"\\' else "\\u{%x}" % ord(c) for c in s) + '"'


def main():
    named = sorted(html.entities.html5.items())
    invalid = sorted(html._invalid_charrefs.items())
    drop = sorted(html._invalid_codepoints)
    lines = [f"//! GENERATED by rust/tools/gen_html_entities.py from Python {sys.version.split()[0]} (`html.entities.html5`, `html._invalid_charrefs`, `html._invalid_codepoints`). Do not edit.",
             "", "/// (name as in `html.entities.html5`, with or without the closing `;`; the text it stands for), sorted by name.", "pub static NAMED: &[(&str, &str)] = &["]
    lines += [f"    ({lit(k)}, {lit(v)})," for k, v in named]
    lines += ["];", "", "/// Numeric references that HTML 5 replaces: (number, replacement), sorted by number.", "pub static INVALID_CHARREFS: &[(u32, &str)] = &["]
    lines += [f"    ({k}, {lit(v)})," for k, v in invalid]
    lines += ["];", "", "/// Numeric references that give nothing, sorted.", "pub static INVALID_CODEPOINTS: &[u32] = &["]
    lines += [f"    {c}," for c in drop]
    lines += ["];", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(OUT, len(named), "names,", len(invalid), "replacements,", len(drop), "dropped")


if __name__ == "__main__":
    main()
